# subjects.py — переключатели «Судьи ЦФО» (субъект РФ) и «Региональная
# федерация» (местное отделение / муниципальное образование) в шапке.
#
# В отличие от REGTEAM_RAFTING, здесь это НЕ обязательная область
# видимости всего приложения, а необязательный фильтр списка судей по
# уже существующим свободнотекстовым полям Judge.region / Judge.municipality
# (точное совпадение по наименованию) — судья как был внесён со
# свободным текстом в этих полях, так и остаётся, справочники Subject/
# LocalBranch лишь дают готовые пункты меню для переключения и список
# отфильтрованных судей.
#
# Субъект хранится в сессии НЕОБЯЗАТЕЛЬНО (в отличие от REGTEAM_RAFTING,
# где всегда есть субъект по умолчанию) — пока субъект не выбран, шапка
# показывает «Судьи ЦФО» и список не фильтруется (видны судьи всех
# субъектов). Местное отделение вложено в субъект (как Organization в
# REGTEAM_RAFTING) — выбор субъекта сбрасывает выбранное отделение.
from flask import session

from models import LocalBranch, SchemaFlag, Subject, db

# Субъекты Центрального федерального округа — сидируются один раз при
# первом запуске, дальше список пополняется через «+ Добавить».
ЦФО_СУБЪЕКТЫ = [
    "Белгородская область",
    "Город Москва",
    "Липецкая область",
    "Московская область",
    "Рязанская область",
]

# Первая версия сидировала все 18 субъектов ЦФО — эти лишние (не входящие
# в текущий ЦФО_СУБЪЕКТЫ) убираются одноразовой идемпотентной миграцией
# _убрать_лишние_субъекты_цфо() ниже на уже запущенных базах.
_ИСКЛЮЧЁННЫЕ_ИЗ_СИДА_СУБЪЕКТЫ = [
    "Брянская область",
    "Владимирская область",
    "Воронежская область",
    "Ивановская область",
    "Калужская область",
    "Костромская область",
    "Курская область",
    "Орловская область",
    "Смоленская область",
    "Тамбовская область",
    "Тверская область",
    "Тульская область",
    "Ярославская область",
]


def обеспечить_субъекты_цфо():
    """Создаёт справочный список субъектов ЦФО, если он ещё пуст (первый
    запуск после появления этой фичи) — дальше ничего не делает."""
    if Subject.query.first():
        return
    for name in ЦФО_СУБЪЕКТЫ:
        db.session.add(Subject(name=name))
    db.session.commit()


_ФЛАГ_УБРАНЫ_ЛИШНИЕ_СУБЪЕКТЫ = "subjects_цфо_урезаны_до_5"


def убрать_лишние_субъекты_цфо():
    """Одноразовая починка: первая версия сидировала все 18 субъектов
    ЦФО, теперь список сокращён до 5 основных — убирает ранее засеянные
    лишние записи (вместе с их местными отделениями, каскадно) на уже
    запущенных базах. Отмечается флагом SchemaFlag, а не просто
    отсутствием подходящих записей — иначе эта же миграция стирала бы
    субъект, который пользователь сам добавит позже под тем же
    названием (например, снова «Тверская область»)."""
    if SchemaFlag.query.get(_ФЛАГ_УБРАНЫ_ЛИШНИЕ_СУБЪЕКТЫ):
        return
    лишние = Subject.query.filter(Subject.name.in_(_ИСКЛЮЧЁННЫЕ_ИЗ_СИДА_СУБЪЕКТЫ)).all()
    for subject in лишние:
        db.session.delete(subject)
    db.session.add(SchemaFlag(key=_ФЛАГ_УБРАНЫ_ЛИШНИЕ_СУБЪЕКТЫ))
    db.session.commit()


def текущий_субъект_id():
    return session.get("judge_subject_id")


def текущий_субъект():
    subject_id = текущий_субъект_id()
    return Subject.query.get(subject_id) if subject_id else None


def местные_отделения_субъекта(subject_id):
    if not subject_id:
        return []
    return LocalBranch.query.filter_by(subject_id=subject_id).order_by(LocalBranch.name).all()


def текущее_местное_отделение_id():
    return session.get("judge_local_branch_id")


def текущее_местное_отделение():
    branch_id = текущее_местное_отделение_id()
    return LocalBranch.query.get(branch_id) if branch_id else None
